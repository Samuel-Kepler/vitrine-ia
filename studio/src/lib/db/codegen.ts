// Diagrama ER -> SQL (Postgres, MySQL, SQLite), Prisma, Drizzle e DBML.
// Tudo determinístico: mesma entrada, mesma saída, funciona offline.
import { camel, fkColumns, joinTables, pascal, pkOf, singular, snake, type ColType, type Column, type ErModel, type Table } from "./model";

export type Dialect = "postgres" | "mysql" | "sqlite";
export interface GeneratedFile {
  path: string;
  content: string;
}

const SQL_TYPES: Record<Dialect, Record<ColType, string>> = {
  postgres: { uuid: "uuid", text: "text", varchar: "varchar(255)", int: "integer", bigint: "bigint", decimal: "numeric(12,2)", boolean: "boolean", timestamp: "timestamptz", date: "date", json: "jsonb" },
  mysql: { uuid: "char(36)", text: "text", varchar: "varchar(255)", int: "int", bigint: "bigint", decimal: "decimal(12,2)", boolean: "boolean", timestamp: "datetime(3)", date: "date", json: "json" },
  sqlite: { uuid: "text", text: "text", varchar: "text", int: "integer", bigint: "integer", decimal: "numeric", boolean: "integer", timestamp: "text", date: "text", json: "text" },
};

const q = (d: Dialect, id: string) => (d === "mysql" ? `\`${id}\`` : `"${id}"`);

function literal(v: string): string {
  if (/^-?\d+(\.\d+)?$/.test(v) || /^(true|false|null)$/i.test(v)) return v;
  return `'${v.replace(/'/g, "''")}'`;
}

function sqlDefault(d: Dialect, c: Column): string {
  const v = c.default?.trim();
  if (!v || v === "autoincrement") return "";
  if (v === "now") return d === "mysql" ? " DEFAULT CURRENT_TIMESTAMP(3)" : " DEFAULT CURRENT_TIMESTAMP";
  if (v === "uuid") return d === "postgres" ? " DEFAULT gen_random_uuid()" : d === "mysql" ? " DEFAULT (UUID())" : "";
  return ` DEFAULT ${literal(v)}`;
}

function sqlColumn(d: Dialect, c: Column, singlePk: boolean): string {
  const auto = c.default === "autoincrement" && (c.type === "int" || c.type === "bigint");
  let type = SQL_TYPES[d][c.type];
  let extra = "";
  if (auto) {
    if (d === "postgres") extra = " GENERATED BY DEFAULT AS IDENTITY";
    if (d === "mysql") extra = " AUTO_INCREMENT";
    if (d === "sqlite") type = "integer";
  }
  const pk = c.pk && singlePk ? (d === "sqlite" && auto ? " PRIMARY KEY AUTOINCREMENT" : " PRIMARY KEY") : "";
  const nn = c.pk || !c.nullable ? " NOT NULL" : "";
  const uq = c.unique && !c.pk ? " UNIQUE" : "";
  return `  ${q(d, snake(c.name))} ${type}${extra}${pk}${pk ? "" : nn}${uq}${sqlDefault(d, c)}`;
}

export function toSql(model: ErModel, d: Dialect): string {
  const fks = fkColumns(model);
  const out: string[] = [`-- Gerado pelo Vitrine Studio (${d})`, ""];
  if (d === "sqlite") out.push("PRAGMA foreign_keys = ON;", "");
  const ordered = topoOrder(model);
  for (const t of ordered) {
    const pks = t.columns.filter((c) => c.pk);
    const lines = t.columns.map((c) => sqlColumn(d, c, pks.length === 1));
    for (const fk of fks.filter((f) => f.table.id === t.id)) {
      lines.push(`  ${q(d, fk.name)} ${SQL_TYPES[d][fk.type]}${fk.nullable ? "" : " NOT NULL"}${fk.unique ? " UNIQUE" : ""}`);
    }
    if (pks.length > 1) lines.push(`  PRIMARY KEY (${pks.map((c) => q(d, snake(c.name))).join(", ")})`);
    for (const fk of fks.filter((f) => f.table.id === t.id)) {
      lines.push(
        `  FOREIGN KEY (${q(d, fk.name)}) REFERENCES ${q(d, snake(fk.ref.name))} (${q(d, snake(fk.refColumn))}) ON DELETE ${fk.onDelete.toUpperCase()}`,
      );
    }
    out.push(`CREATE TABLE ${q(d, snake(t.name))} (\n${lines.join(",\n")}\n);`, "");
    for (const fk of fks.filter((f) => f.table.id === t.id && !f.unique)) {
      out.push(`CREATE INDEX ${q(d, `${snake(t.name)}_${fk.name}_idx`)} ON ${q(d, snake(t.name))} (${q(d, fk.name)});`);
    }
    if (fks.some((f) => f.table.id === t.id && !f.unique)) out.push("");
  }
  for (const j of joinTables(model)) {
    const ap = pkOf(j.a);
    const bp = pkOf(j.b);
    const an = `${singular(snake(j.a.name))}_id`;
    const bn = `${singular(snake(j.b.name))}_id`;
    out.push(
      `CREATE TABLE ${q(d, j.name)} (\n` +
        `  ${q(d, an)} ${SQL_TYPES[d][ap?.type ?? "uuid"]} NOT NULL,\n` +
        `  ${q(d, bn)} ${SQL_TYPES[d][bp?.type ?? "uuid"]} NOT NULL,\n` +
        `  PRIMARY KEY (${q(d, an)}, ${q(d, bn)}),\n` +
        `  FOREIGN KEY (${q(d, an)}) REFERENCES ${q(d, snake(j.a.name))} (${q(d, snake(ap?.name ?? "id"))}) ON DELETE CASCADE,\n` +
        `  FOREIGN KEY (${q(d, bn)}) REFERENCES ${q(d, snake(j.b.name))} (${q(d, snake(bp?.name ?? "id"))}) ON DELETE CASCADE\n);`,
      "",
    );
  }
  return out.join("\n").trimEnd() + "\n";
}

/** Pais antes dos filhos (para os REFERENCES funcionarem); ciclos vão no fim. */
function topoOrder(model: ErModel): Table[] {
  const fks = fkColumns(model);
  const done = new Set<string>();
  const out: Table[] = [];
  let guard = 0;
  while (out.length < model.tables.length && guard++ < model.tables.length + 2) {
    for (const t of model.tables) {
      if (done.has(t.id)) continue;
      const deps = fks.filter((f) => f.table.id === t.id && f.ref.id !== t.id).map((f) => f.ref.id);
      if (deps.every((id) => done.has(id))) {
        done.add(t.id);
        out.push(t);
      }
    }
  }
  return [...out, ...model.tables.filter((t) => !done.has(t.id))];
}

// ---------------- Prisma ----------------

const PRISMA_TYPES: Record<ColType, string> = {
  uuid: "String @db.Uuid",
  text: "String",
  varchar: "String @db.VarChar(255)",
  int: "Int",
  bigint: "BigInt",
  decimal: "Decimal @db.Decimal(12, 2)",
  boolean: "Boolean",
  timestamp: "DateTime @db.Timestamptz(3)",
  date: "DateTime @db.Date",
  json: "Json",
};

function prismaType(t: ColType, optional: boolean): string {
  const [base, ...attrs] = PRISMA_TYPES[t].split(" ");
  return [base + (optional ? "?" : ""), ...attrs].join(" ");
}

function prismaDefault(c: Column): string {
  const v = c.default?.trim();
  if (!v) return "";
  if (v === "now") return " @default(now())";
  if (v === "uuid") return " @default(uuid())";
  if (v === "autoincrement") return " @default(autoincrement())";
  if (/^-?\d+(\.\d+)?$/.test(v) || /^(true|false)$/.test(v)) return ` @default(${v})`;
  return ` @default(${JSON.stringify(v)})`;
}

const PRISMA_ON_DELETE = { cascade: "Cascade", "set null": "SetNull", restrict: "Restrict" } as const;

export function toPrisma(model: ErModel): string {
  const fks = fkColumns(model);
  const joins = joinTables(model);
  const name = (t: Table) => pascal(singular(snake(t.name)));
  const out = [
    "// Gerado pelo Vitrine Studio",
    "generator client {",
    '  provider = "prisma-client-js"',
    "}",
    "",
    "datasource db {",
    '  provider = "postgresql"',
    '  url      = env("DATABASE_URL")',
    "}",
    "",
  ];
  for (const t of model.tables) {
    const lines: string[] = [];
    const pks = t.columns.filter((c) => c.pk);
    for (const c of t.columns) {
      const attrs = [c.pk && pks.length === 1 ? " @id" : "", c.unique && !c.pk ? " @unique" : "", prismaDefault(c)].join("");
      const field = camel(c.name);
      const map = field !== snake(c.name) ? ` @map("${snake(c.name)}")` : "";
      lines.push(`  ${field} ${prismaType(c.type, !!c.nullable && !c.pk)}${attrs}${map}`);
    }
    for (const fk of fks.filter((f) => f.table.id === t.id)) {
      const field = camel(fk.name);
      const rel = camel(singular(snake(fk.ref.name)));
      lines.push(`  ${field} ${prismaType(fk.type, fk.nullable)}${fk.unique ? " @unique" : ""}${field !== fk.name ? ` @map("${fk.name}")` : ""}`);
      lines.push(
        `  ${rel} ${name(fk.ref)}${fk.nullable ? "?" : ""} @relation("${fk.relation.id}", fields: [${field}], references: [${camel(fk.refColumn)}], onDelete: ${PRISMA_ON_DELETE[fk.onDelete]})`,
      );
    }
    for (const fk of fks.filter((f) => f.ref.id === t.id)) {
      const child = name(fk.table);
      lines.push(`  ${camel(fk.unique ? singular(snake(fk.table.name)) : snake(fk.table.name))} ${child}${fk.unique ? "?" : "[]"} @relation("${fk.relation.id}")`);
    }
    for (const j of joins.filter((j) => j.a.id === t.id || j.b.id === t.id)) {
      lines.push(`  ${camel(j.name)} ${pascal(j.name)}[]`);
    }
    if (pks.length > 1) lines.push(`\n  @@id([${pks.map((c) => camel(c.name)).join(", ")}])`);
    lines.push(`  @@map("${snake(t.name)}")`);
    out.push(`model ${name(t)} {`, ...lines, "}", "");
  }
  for (const j of joins) {
    const an = camel(`${singular(snake(j.a.name))}_id`);
    const bn = camel(`${singular(snake(j.b.name))}_id`);
    const ap = pkOf(j.a);
    const bp = pkOf(j.b);
    out.push(
      `model ${pascal(j.name)} {`,
      `  ${an} ${prismaType(ap?.type ?? "uuid", false)} @map("${singular(snake(j.a.name))}_id")`,
      `  ${bn} ${prismaType(bp?.type ?? "uuid", false)} @map("${singular(snake(j.b.name))}_id")`,
      `  ${camel(singular(snake(j.a.name)))} ${name(j.a)} @relation(fields: [${an}], references: [${camel(ap?.name ?? "id")}], onDelete: Cascade)`,
      `  ${camel(singular(snake(j.b.name)))} ${name(j.b)} @relation(fields: [${bn}], references: [${camel(bp?.name ?? "id")}], onDelete: Cascade)`,
      "",
      `  @@id([${an}, ${bn}])`,
      `  @@map("${j.name}")`,
      "}",
      "",
    );
  }
  return out.join("\n").trimEnd() + "\n";
}

// ---------------- Drizzle (pg-core) ----------------

const DRIZZLE: Record<ColType, (n: string) => string> = {
  uuid: (n) => `uuid("${n}")`,
  text: (n) => `text("${n}")`,
  varchar: (n) => `varchar("${n}", { length: 255 })`,
  int: (n) => `integer("${n}")`,
  bigint: (n) => `bigint("${n}", { mode: "number" })`,
  decimal: (n) => `numeric("${n}", { precision: 12, scale: 2 })`,
  boolean: (n) => `boolean("${n}")`,
  timestamp: (n) => `timestamp("${n}", { withTimezone: true })`,
  date: (n) => `date("${n}")`,
  json: (n) => `jsonb("${n}")`,
};

function drizzleCol(c: Column, singlePk: boolean): string {
  let s = DRIZZLE[c.type](snake(c.name));
  const v = c.default?.trim();
  if (v === "autoincrement" && (c.type === "int" || c.type === "bigint")) s += ".generatedByDefaultAsIdentity()";
  if (c.pk && singlePk) s += ".primaryKey()";
  if (!c.pk && !c.nullable) s += ".notNull()";
  if (c.unique && !c.pk) s += ".unique()";
  if (v === "now") s += ".defaultNow()";
  else if (v === "uuid") s += ".defaultRandom()";
  else if (v && v !== "autoincrement") s += `.default(${/^-?\d+(\.\d+)?$/.test(v) || /^(true|false)$/.test(v) ? v : JSON.stringify(v)})`;
  return s;
}

export function toDrizzle(model: ErModel): string {
  const fks = fkColumns(model);
  const used = new Set<string>(["pgTable"]);
  const varName = (t: Table) => camel(snake(t.name));
  const body: string[] = [];
  const fn = (s: string) => used.add(s.slice(0, s.indexOf("(")));
  for (const t of topoOrder(model)) {
    const pks = t.columns.filter((c) => c.pk);
    const cols = t.columns.map((c) => {
      const s = drizzleCol(c, pks.length === 1);
      fn(s);
      return `  ${camel(c.name)}: ${s},`;
    });
    for (const fk of fks.filter((f) => f.table.id === t.id)) {
      const s = DRIZZLE[fk.type](fk.name);
      fn(s);
      cols.push(
        `  ${camel(fk.name)}: ${s}${fk.nullable ? "" : ".notNull()"}${fk.unique ? ".unique()" : ""}.references(() => ${varName(fk.ref)}.${camel(fk.refColumn)}, { onDelete: "${fk.onDelete}" }),`,
      );
    }
    const extra = pks.length > 1 ? `, (t) => [primaryKey({ columns: [${pks.map((c) => `t.${camel(c.name)}`).join(", ")}] })]` : "";
    if (extra) used.add("primaryKey");
    body.push(`export const ${varName(t)} = pgTable("${snake(t.name)}", {\n${cols.join("\n")}\n}${extra});`, "");
  }
  for (const j of joinTables(model)) {
    const ap = pkOf(j.a);
    const bp = pkOf(j.b);
    const an = `${singular(snake(j.a.name))}_id`;
    const bn = `${singular(snake(j.b.name))}_id`;
    const sa = DRIZZLE[ap?.type ?? "uuid"](an);
    const sb = DRIZZLE[bp?.type ?? "uuid"](bn);
    fn(sa);
    fn(sb);
    used.add("primaryKey");
    body.push(
      `export const ${camel(j.name)} = pgTable("${j.name}", {\n` +
        `  ${camel(an)}: ${sa}.notNull().references(() => ${varName(j.a)}.${camel(ap?.name ?? "id")}, { onDelete: "cascade" }),\n` +
        `  ${camel(bn)}: ${sb}.notNull().references(() => ${varName(j.b)}.${camel(bp?.name ?? "id")}, { onDelete: "cascade" }),\n` +
        `}, (t) => [primaryKey({ columns: [t.${camel(an)}, t.${camel(bn)}] })]);`,
      "",
    );
  }
  return [`// Gerado pelo Vitrine Studio`, `import { ${[...used].sort().join(", ")} } from "drizzle-orm/pg-core";`, "", ...body].join("\n").trimEnd() + "\n";
}

// ---------------- DBML ----------------

export function toDbml(model: ErModel): string {
  const fks = fkColumns(model);
  const out = ["// Gerado pelo Vitrine Studio — abra em dbdiagram.io", ""];
  for (const t of model.tables) {
    out.push(`Table ${snake(t.name)} {`);
    for (const c of t.columns) {
      const attrs = [c.pk ? "pk" : "", c.pk || c.nullable ? "" : "not null", c.unique && !c.pk ? "unique" : "", c.default === "autoincrement" ? "increment" : ""];
      if (c.default && !["autoincrement"].includes(c.default)) attrs.push(`default: ${c.default === "now" ? "`now()`" : c.default === "uuid" ? "`gen_random_uuid()`" : literal(c.default)}`);
      const a = attrs.filter(Boolean);
      out.push(`  ${snake(c.name)} ${SQL_TYPES.postgres[c.type]}${a.length ? ` [${a.join(", ")}]` : ""}`);
    }
    for (const fk of fks.filter((f) => f.table.id === t.id)) {
      out.push(`  ${fk.name} ${SQL_TYPES.postgres[fk.type]}${fk.nullable ? "" : " [not null]"}`);
    }
    out.push("}", "");
  }
  for (const fk of fks) {
    out.push(`Ref: ${snake(fk.table.name)}.${fk.name} ${fk.unique ? "-" : ">"} ${snake(fk.ref.name)}.${snake(fk.refColumn)} [delete: ${fk.onDelete}]`);
  }
  for (const j of joinTables(model)) {
    out.push(`Ref: ${snake(j.a.name)}.${snake(pkOf(j.a)?.name ?? "id")} <> ${snake(j.b.name)}.${snake(pkOf(j.b)?.name ?? "id")}`);
  }
  return out.join("\n").trimEnd() + "\n";
}

export function dbFiles(model: ErModel): GeneratedFile[] {
  return [
    { path: "db/schema.postgres.sql", content: toSql(model, "postgres") },
    { path: "db/schema.mysql.sql", content: toSql(model, "mysql") },
    { path: "db/schema.sqlite.sql", content: toSql(model, "sqlite") },
    { path: "db/prisma/schema.prisma", content: toPrisma(model) },
    { path: "db/drizzle/schema.ts", content: toDrizzle(model) },
    { path: "db/schema.dbml", content: toDbml(model) },
  ];
}
